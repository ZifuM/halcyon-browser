"""Copy Firefox's [patch.crates-io] table into crates/*/Cargo.toml (paths re-rooted at engine/).

Firefox remaps some crate versions to local shims; our crates build against Firefox's vendored
crates, so they need the same remapping. Run after `hx download` / a rebase:
    python3 tools/shield/sync_cargo_patches.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MARKER = "# Mirrors [patch.crates-io] in Firefox's root Cargo.toml"


def firefox_patches(engine: Path) -> list[str]:
    text = (engine / "Cargo.toml").read_text(encoding="utf-8")
    m = re.search(r"^\[patch\.crates-io\]\n(.*?)(?=^\[|\Z)", text, re.S | re.M)
    if not m:
        sys.exit("No [patch.crates-io] in engine/Cargo.toml")
    out = []
    for line in m.group(1).splitlines():
        if not line.strip() or line.strip().startswith("#"):
            continue
        path = re.search(r'path = "([^"]+)"', line)
        # Keep only local shims that exist in our (sparse) checkout; git/registry patches and
        # parts of Firefox we don't fetch aren't needed by our crates.
        if not path or not (engine / path.group(1) / "Cargo.toml").is_file():
            continue
        out.append(line.replace(f'path = "{path.group(1)}"', f'path = "../../engine/{path.group(1)}"'))
    return out


def sync(manifest: Path, patches: list[str]) -> None:
    text = manifest.read_text(encoding="utf-8")
    if MARKER in text:
        text = text[: text.index(MARKER)].rstrip() + "\n"
    text = text.rstrip() + f"\n\n{MARKER} (generated by tools/shield/sync_cargo_patches.py)\n"
    text += "[patch.crates-io]\n" + "\n".join(patches) + "\n"
    manifest.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    patches = firefox_patches(ROOT / "engine")
    for manifest in sorted((ROOT / "crates").glob("*/Cargo.toml")):
        sync(manifest, patches)
        print(f"{manifest.relative_to(ROOT)}: {len(patches)} patch entries")


if __name__ == "__main__":
    main()
