"""Wrappers around Mozilla's `mach`: write the mozconfig, bootstrap, build, run, package."""

from __future__ import annotations

import os
import platform
import re
import shutil
import sys
from pathlib import Path

from .config import Project
from .engine import read_state
from .util import HxError, info, ok, render, run, warn


def host_os() -> str:
    system = platform.system()
    return {"Darwin": "macos", "Windows": "windows"}.get(system, "linux")


def compose_mozconfig(project: Project, target_os: str, profile: str) -> str:
    """configs/common.mozconfig + configs/<os>.mozconfig + configs/<profile>.mozconfig."""
    parts = []
    for name in ("common", target_os, profile):
        path = project.configs_dir / f"{name}.mozconfig"
        if not path.is_file():
            raise HxError(f"Missing {path.relative_to(project.root)}")
        parts.append(f"# ---- {path.name} ----\n" + path.read_text(encoding="utf-8").strip() + "\n")
    extra = os.environ.get("HX_MOZCONFIG_EXTRA", "").strip()
    if extra:  # machine-local additions, e.g. CI's compiler cache; never committed
        parts.append("# ---- $HX_MOZCONFIG_EXTRA ----\n" + extra.replace("\\n", "\n") + "\n")
    text = "# Generated by `hx build` from configs/*.mozconfig. Do not edit here.\n\n" + "\n".join(parts)
    return render(text, project.tokens(), "configs/*.mozconfig")


OS_CHOICES = ("linux", "macos", "windows")
PROFILE_CHOICES = ("release", "dev", "artifact")
# Options handled by mach/the configure wrapper itself rather than an option() declaration.
BUILTIN_OPTIONS = {"--target", "--host"}


def _declared_options(engine: Path) -> tuple[set[str], set[str]]:
    """All option names (--foo) and env names (FOO) declared in the engine's *.configure files."""
    flags, envs = set(), set()
    roots = [engine / "moz.configure", *sorted((engine / "build" / "moz.configure").glob("*.configure"))]
    for sub in ("toolkit", "browser", "js"):
        roots += sorted((engine / sub).glob("*.configure"))
    for path in roots:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'(?:option|project_flag)\(', text):
            chunk = text[m.end(): m.end() + 400]
            flag = re.match(r'\s*"(--[a-z0-9-]+)"', chunk)
            if flag:
                flags.add(flag.group(1))
            env = re.search(r'env="([A-Z0-9_]+)"', chunk.split("\n)\n")[0])
            if env:
                envs.add(env.group(1))
    return flags, envs


def _canonical(flag: str) -> list[str]:
    """--disable-foo -> --enable-foo; --without-foo -> --with-foo (either may be declared)."""
    for neg, pos in (("--disable-", "--enable-"), ("--without-", "--with-")):
        if flag.startswith(neg):
            return [pos + flag[len(neg):], flag]
    for pos, neg in (("--enable-", "--disable-"), ("--with-", "--without-")):
        if flag.startswith(pos):
            return [flag, neg + flag[len(pos):]]
    return [flag]


def validate_mozconfigs(project: Project) -> list[str]:
    """Check every ac_add_options in every OS x profile mozconfig against upstream declarations."""
    flags, envs = _declared_options(project.engine)
    if not flags:
        raise HxError("No *.configure files in engine/ (download first).")
    problems = []
    for target_os in OS_CHOICES:
        for profile in PROFILE_CHOICES:
            text = compose_mozconfig(project, target_os, profile)
            for line in text.splitlines():
                line = line.split("#", 1)[0].strip()
                if not line.startswith("ac_add_options "):
                    continue
                arg = line.split(None, 1)[1].strip()
                name = arg.split("=", 1)[0]
                if name in BUILTIN_OPTIONS:
                    continue
                if name.startswith("--"):
                    if not any(c in flags for c in _canonical(name)):
                        problems.append(f"{target_os}/{profile}: unknown option {name}")
                elif name not in envs:
                    problems.append(f"{target_os}/{profile}: unknown variable {name}")
    return sorted(set(problems))


def write_mozconfig(project: Project, target_os: str | None = None, profile: str = "release") -> Path:
    read_state(project.engine)
    target_os = target_os or host_os()
    if profile not in ("release", "dev", "artifact"):
        raise HxError("profile must be release, dev or artifact")
    path = project.engine / "mozconfig"
    path.write_text(compose_mozconfig(project, target_os, profile), encoding="utf-8", newline="\n")
    ok(f"Wrote engine/mozconfig ({target_os}, {profile})")
    return path


def _mach(project: Project, *args: str) -> None:
    engine = project.engine
    if not (engine / "mach").is_file():
        raise HxError("engine/mach not found. Full (non-sparse) `hx download` needed to build.")
    if read_state(engine).get("sparse"):
        raise HxError("engine/ is a sparse checkout (CI checks only). Run `hx download --force` for a full tree.")
    # Our launcher sets PYTHONPATH for hx itself; mach manages its own virtualenv, so drop it.
    env = {"MOZCONFIG": str(engine / "mozconfig"), "PYTHONPATH": None}
    run([sys.executable, str(engine / "mach"), *args], cwd=engine, env=env)


def bootstrap(project: Project) -> None:
    info("Installing Mozilla's build toolchains (clang, rust, node...) via mach bootstrap")
    _mach(project, "--no-interactive", "bootstrap", "--application-choice", "browser")


def build(project: Project, target_os: str | None = None, profile: str = "release") -> None:
    if not read_state(project.engine).get("import_commit"):
        raise HxError("Run `hx import` before building.")
    write_mozconfig(project, target_os, profile)
    info("Building (first build takes 1-3 hours; later builds are incremental)")
    _mach(project, "build")
    ok("Build finished. Try `hx run`.")


def run_browser(project: Project, extra: list[str]) -> None:
    _mach(project, "run", *extra)


def package(project: Project, target_os: str | None = None) -> None:
    """Make the distributable. On Windows, `mach package` builds both the portable .zip and the
    NSIS setup .exe (toolkit/mozapps/installer/packager.mk: make-package -> windows installer)."""
    target_os = target_os or host_os()
    _mach(project, "package")
    if target_os == "windows":
        ok("Installer: engine/obj-*/dist/*.installer.exe  (portable: dist/*.zip)")
    elif target_os == "macos":
        ok("Disk image: engine/obj-*/dist/*.dmg")
    else:
        ok("Archive: engine/obj-*/dist/*.tar.xz")


def doctor(project: Project) -> list[str]:
    """Return a list of problems that would stop a build on this machine."""
    problems = []
    if sys.version_info < (3, 11):
        problems.append("Python 3.11+ is required")
    if not shutil.which("git"):
        problems.append("git not found on PATH")
    free_gb = shutil.disk_usage(project.root).free / 1e9
    if free_gb < 40:
        problems.append(f"Only {free_gb:.0f} GB free; a Firefox build needs ~40 GB")
    mem_gb = _memory_gb()
    if mem_gb is not None and mem_gb < 16:
        warn(f"{mem_gb:.0f} GB RAM detected; 16 GB+ recommended (builds will be slow)")
    os_name = host_os()
    if os_name == "windows" and not os.environ.get("MOZILLABUILD"):
        problems.append("Run hx from the MozillaBuild shell on Windows (see docs/BUILDING.md)")
    if os_name == "macos" and not shutil.which("xcode-select"):
        problems.append("Xcode command line tools not found")
    return problems


def _memory_gb() -> float | None:
    try:
        if hasattr(os, "sysconf") and "SC_PHYS_PAGES" in os.sysconf_names:
            return os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES") / 1e9
    except (ValueError, OSError):
        pass
    return None
