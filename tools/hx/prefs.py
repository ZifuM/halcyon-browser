"""Default preferences: prefs/*.toml -> a JS defaults file baked into the build.

Design rules (enforced here):
  * Only `pref()` defaults are emitted. Nothing is ever locked: the user can change any of them,
    and because these are defaults (not user values), updates never overwrite a user's choice.
  * Every pref must exist upstream. `hx audit-prefs` checks names against the Firefox source so a
    renamed or removed pref is caught at rebase time instead of silently doing nothing.
"""

from __future__ import annotations

import json
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path

from .util import HxError

NAME_RE = re.compile(r"^[A-Za-z0-9_.\-\[\]@{}]+$")

# Upstream files where pref defaults normally live (checked in this order).
DEFAULT_LOCATIONS = (
    "modules/libpref/init/StaticPrefList.yaml",
    "modules/libpref/init/all.js",
    "browser/app/profile/firefox.js",
)


@dataclass(frozen=True)
class Pref:
    name: str
    value: bool | int | str
    why: str
    source_file: str
    upstream: str | None = None
    match: str | None = None   # string to look for in `upstream` when the code uses a short key
    own: bool = False          # defined by our src/ code rather than by Firefox


@dataclass(frozen=True)
class PrefGroup:
    file: str
    title: str
    prefs: tuple[Pref, ...]


def load_groups(prefs_dir: Path) -> list[PrefGroup]:
    groups: list[PrefGroup] = []
    seen: dict[str, str] = {}
    for path in sorted(prefs_dir.glob("*.toml")):
        with open(path, "rb") as fh:
            try:
                data = tomllib.load(fh)
            except tomllib.TOMLDecodeError as exc:
                raise HxError(f"{path.name}: invalid TOML: {exc}") from None
        title = data.get("meta", {}).get("title", path.stem)
        prefs = []
        for i, entry in enumerate(data.get("pref", []), start=1):
            where = f"{path.name} entry {i}"
            unknown = set(entry) - {"name", "value", "why", "upstream", "match", "own"}
            if unknown:
                raise HxError(f"{where}: unknown keys {sorted(unknown)}")
            for key in ("name", "value", "why"):
                if key not in entry:
                    raise HxError(f"{where}: missing '{key}'")
            name, value, why = entry["name"], entry["value"], entry["why"]
            if not isinstance(name, str) or not NAME_RE.match(name):
                raise HxError(f"{where}: invalid pref name {name!r}")
            if isinstance(value, float) or not isinstance(value, (bool, int, str)):
                raise HxError(f"{where}: {name} must be a bool, int or string (floats go in quotes)")
            if isinstance(value, int) and not isinstance(value, bool) and not (-(2**31) <= value < 2**31):
                raise HxError(f"{where}: {name} int out of 32-bit range")
            if not str(why).strip():
                raise HxError(f"{where}: {name} needs a 'why' explaining the change")
            if name in seen:
                raise HxError(f"{name} is set in both {seen[name]} and {path.name}")
            seen[name] = path.name
            if "match" in entry and "upstream" not in entry:
                raise HxError(f"{where}: {name} has 'match' but no 'upstream' file")
            if entry.get("own") and ("upstream" in entry or "match" in entry):
                raise HxError(f"{where}: {name} is 'own' and can't also name an upstream file")
            prefs.append(Pref(name, value, why.strip(), path.name, entry.get("upstream"),
                              entry.get("match"), bool(entry.get("own", False))))
        groups.append(PrefGroup(path.name, title, tuple(prefs)))
    return groups


def js_value(value: bool | int | str) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def compile_js(groups: list[PrefGroup], product_name: str) -> str:
    lines = [
        "",
        f"// ---- {product_name} defaults ------------------------------------------------",
        "// Generated by `hx import` from prefs/*.toml. Do not edit here.",
        "// These are defaults only: nothing is locked, and a user's own choice always wins.",
    ]
    for group in groups:
        if not group.prefs:
            continue
        lines += ["", f"// {group.title}  ({group.file})"]
        for pref in group.prefs:
            for why_line in pref.why.splitlines():
                lines.append(f"// {why_line}")
            lines.append(f"pref({json.dumps(pref.name)}, {js_value(pref.value)});")
    return "\n".join(lines) + "\n"


# ---- audit --------------------------------------------------------------

@dataclass
class AuditResult:
    verified: dict[str, str]          # pref -> file it was found in
    unverified: list[Pref]
    missing_files: set[str]


def _defined_in(text: str, name: str, is_yaml: bool) -> bool:
    if is_yaml:
        return re.search(rf"(?m)^-\s+name:\s+{re.escape(name)}\s*$", text) is not None
    return f'"{name}"' in text or f"'{name}'" in text


def _own_sources(src_dir: Path | None) -> str:
    if not src_dir or not src_dir.is_dir():
        return ""
    chunks = []
    for p in sorted(src_dir.rglob("*")):
        if p.is_file() and p.suffix in {".mjs", ".js", ".jsm", ".xhtml", ".html", ".cpp", ".rs"}:
            chunks.append(p.read_text(encoding="utf-8", errors="replace"))
    return "\n".join(chunks)


def audit(groups: list[PrefGroup], engine: Path, src_dir: Path | None = None) -> AuditResult:
    cache: dict[str, str | None] = {}

    def read(rel: str) -> str | None:
        if rel not in cache:
            p = engine / rel
            cache[rel] = p.read_text(encoding="utf-8", errors="replace") if p.is_file() else None
        return cache[rel]

    result = AuditResult({}, [], set())
    own_text = None
    for group in groups:
        for pref in group.prefs:
            if pref.own:
                if own_text is None:
                    own_text = _own_sources(src_dir)
                if _defined_in(own_text, pref.name, False):
                    result.verified[pref.name] = "src/ (own)"
                else:
                    result.unverified.append(pref)
                continue
            locations = list(DEFAULT_LOCATIONS)
            if pref.upstream:
                locations.insert(0, pref.upstream)
            found = None
            for rel in locations:
                text = read(rel)
                if text is None:
                    result.missing_files.add(rel)
                    continue
                if _defined_in(text, pref.name, rel.endswith(".yaml")):
                    found = rel
                    break
                if pref.match and rel == pref.upstream and _defined_in(text, pref.match, False):
                    found = f"{rel} (as {pref.match!r})"
                    break
            if found:
                result.verified[pref.name] = found
            else:
                result.unverified.append(pref)
    return result


def upstream_paths(groups: list[PrefGroup]) -> list[str]:
    """Every upstream file the audit needs (for sparse checkouts in CI)."""
    paths = set(DEFAULT_LOCATIONS)
    for group in groups:
        for pref in group.prefs:
            if pref.upstream:
                paths.add(pref.upstream)
    return sorted(paths)
